#!/usr/bin/env python3
"""make_table1.py - regenerate the evaluation summary table from raw run CSVs.

Reads the latest test_bed_qos/workloads/0N_*/results/multi_run_*/results_summary_raw.csv
(or a directory given with --run NAME=PATH) and writes Report/table1.csv and
Report/table1.tex. Cells are median P99 (ms) [95% bootstrap CI of the median], N shown.
Nothing is typed by hand: re-run after every experiment.

Usage: python3 make_table1.py [--flood flood] [--ref qos_tiered] [--target qos_markov]
"""
import argparse
import glob
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
WL = os.path.join(HERE, "..", "test_bed_qos", "workloads")
sys.path.insert(0, os.path.join(WL, "shared"))
import stats_common as sc  # noqa: E402

# workload dir -> (label, metric column, optional row filter column/value placeholder)
WORKLOADS = [
    ("01_steady_state", "01 Steady-state (flood)", "p99_ms", "flood_level"),
    ("02_bursty_oscillating", "02 Bursty oscillating", "p99_ms", None),
    ("03_ramping_escalation", "03 Ramping overload", "p99_ms", None),
    ("04_flash_crowd_victim", "04 Flash-crowd (phase 2)", "phase2_p99_ms", None),
    ("05_multi_tenant_mix", "05 Multi-tenant (Victim 2)", "v2_p99_ms", None),
    ("06_retry_storm", "06 Retry storm", "p99_ms", None),
]
ORDER = ["qos_tc_police", "qos_tc_tbf", "qos_tiered", "qos_percpu_static", "qos_dynamic_fixed", "qos_dynamic_adaptive",
         "qos_markov_200ms", "qos_markov"]


def latest_csv(d, wl=WL):
    runs = sorted(glob.glob(os.path.join(wl, d, "results", "multi_run_*", "results_summary_raw.csv")))
    return runs[-1] if runs else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--flood", default="flood", help="flood level used for workload 01")
    ap.add_argument("--ref", default="qos_tiered", help="reference arm for reductions")
    ap.add_argument("--workloads-dir", default=WL, help="override workloads dir (for testing)")
    ap.add_argument("--out-dir", default=HERE, help="where to write table1.csv/.tex")
    ap.add_argument("--target", default="qos_markov", help="arm whose reduction is reported")
    a = ap.parse_args()

    rows, used = [], {}
    for d, label, metric, filt in WORKLOADS:
        path = latest_csv(d, a.workloads_dir)
        if not path:
            print(f"[skip] {d}: no results", file=sys.stderr)
            continue
        df = pd.read_csv(path)
        if filt:
            df = df[df[filt].astype(str) == a.flood]
        used[d] = os.path.relpath(path, HERE)
        row = {"workload": label, "metric": metric, "source": used[d]}
        for arm in [x for x in ORDER if x in set(df["arch"])]:
            v = df.loc[df["arch"] == arm, metric].dropna().to_numpy(float)
            lo, hi = sc.boot_ci_median(v)
            row[arm] = f"{pd.Series(v).median():.2f} [{lo:.2f}, {hi:.2f}] (n={len(v)})"
            row[arm + "__median"] = float(pd.Series(v).median())
        rows.append(row)
    if not rows:
        sys.exit("no results found; run the workloads first")

    out = pd.DataFrame(rows)
    arms = [x for x in ORDER if x in out.columns]
    # reductions of target vs every other arm, from medians (not typed by hand)
    for other in arms:
        if other != a.target and a.target in arms:
            out[f"reduction_vs_{other}_%"] = 100 * (1 - out[a.target + "__median"] / out[other + "__median"])
    out.drop(columns=[c for c in out.columns if c.endswith("__median")]).to_csv(
        os.path.join(a.out_dir, "table1.csv"), index=False)

    with open(os.path.join(a.out_dir, "table1.tex"), "w") as f:
        f.write("% generated by Report/make_table1.py - do not edit by hand\n")
        f.write("\\begin{tabular}{l" + "r" * len(arms) + "}\n\\toprule\nWorkload & " +
                " & ".join(x.replace("_", "\\_") for x in arms) + " \\\\\n\\midrule\n")
        for _, r in out.iterrows():
            f.write(r["workload"] + " & " + " & ".join(str(r.get(x, "--")) for x in arms) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    print(out.drop(columns=[c for c in out.columns if c.endswith("__median") or c == "source"]).to_string(index=False))
    print("\nwrote Report/table1.csv and Report/table1.tex; sources:")
    for k, v in used.items():
        print(" ", k, "<-", v)


if __name__ == "__main__":
    main()
